const chatBag={},chatLast={};
let chatLastMono=performance.now(),chatLastHurt=-1e9,chatPending=null,chatRichStep=-1;
function chatShuffle(a){for(let i=a.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[a[i],a[j]]=[a[j],a[i]];}return a;}
function chatSub(s){return s.replace(/\{이름\}/g,(P&&P.name)||'루크레아');}
function chatNext(key,pool){
  let b=chatBag[key];
  if(!b||!b.length){
    b=chatShuffle(pool.slice());
    if(b.length>1&&b[b.length-1]===chatLast[key]){const t=b[0];b[0]=b[b.length-1];b[b.length-1]=t;}
    chatBag[key]=b;
  }
  const s=b.pop();chatLast[key]=s;return s;
}
function chatKey(n){if(!n)return null;return CHAT.npc[n.name]?n.name:(CHAT.npc[n.title]?n.title:null);}
function chatTalk(n){const k=chatKey(n);return k?chatSub(chatNext('n:'+k,CHAT.npc[k])):null;}
function chatTalkClick(){if(!talking)return;const s=chatTalk(talking);if(s)$('dlgLine').textContent=s;}
$('dlgTalk').addEventListener('click',chatTalkClick);
$('dlgChat').addEventListener('click',chatTalkClick);

function chatQuiet(now){
  if(!(MAP==='dungeon'||MAP==='field'))return false;
  if(panel||traveling)return false;
  if(window.UI&&UI.isOpen&&UI.isOpen())return false;
  if(now-chatLastHurt<CHAT_CFG.quietAfterHurt*1000)return false;
  if(typeof monsters!=='undefined'&&monsters.some(m=>!m.dead&&Math.hypot(m.x-P.x,m.y-P.y)<CHAT_CFG.nearMonster))return false;
  return true;
}
function chatEvent(kind,delayMs){
  if(P.chatter===false)return false;
  const now=performance.now();
  if(chatPending&&now<chatPending.exp)return false;
  if(now-chatLastMono<CHAT_CFG.monoGap*1000)return false;
  if(Math.random()>(CHAT_CFG.chance[kind]||0))return false;
  const pool=CHAT.mono[kind];if(!pool)return false;
  chatPending={txt:chatSub(chatNext('m:'+kind,pool)),due:now+(delayMs||0),exp:now+6000};
  return true;
}
setInterval(()=>{
  const now=performance.now();
  if(chatPending){
    if(now>chatPending.exp)chatPending=null;
    else if(now>=chatPending.due&&!bubble&&chatQuiet(now)){bubble={txt:chatPending.txt,t:0,dur:CHAT_CFG.monoSec,mono:true};chatLastMono=now;chatPending=null;}
  }
  if(!chatPending&&chatQuiet(now)){
    if(P.hp>0&&P.hp<=P.maxHp*.25)chatEvent('lowhp');
    const steps=[1000,3000,10000,30000,100000],g=P.gold|0;
    if(chatRichStep<0){chatRichStep=steps.filter(x=>g>=x).length;}
    else if(chatRichStep<steps.length&&g>=steps[chatRichStep]){chatRichStep++;chatEvent('rich');}
  }
},300);

window.CHATTER={
  loot(it){if(!it)return;const r=it.rar||0;if(r>=2)chatEvent('rare',1900);else if(r===0)chatEvent('dull',1900);},
  floor(n){if(n>=10)chatEvent('deep10',2000);else if(n>=5)chatEvent('deep',2000);},
  event:chatEvent,
  hurt(){chatLastHurt=performance.now();}
};
// 테스트 훅: mono(상황)은 조건·간격을 무시하고 즉시 한 줄 출력, talk(이름)은 잡담 한 줄 반환.
window.__CHAT={
  cfg:CHAT_CFG,data:CHAT,
  mono(kind){const pool=CHAT.mono[kind];if(!pool)return null;const s=chatSub(chatNext('m:'+kind,pool));bubble={txt:s,t:0,dur:CHAT_CFG.monoSec,mono:true};return s;},
  talk(name){return chatTalk({name,title:name});},
  event:chatEvent,bubble:()=>bubble,
  state:()=>({pending:!!chatPending,quiet:chatQuiet(performance.now()),sinceMono:(performance.now()-chatLastMono)/1000})
};
